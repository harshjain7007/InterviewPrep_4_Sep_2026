// ----------------- Types of Methologys :---------
// There are several software development methodologies that companies use to manage projects and deliver software. Each methodology has its own approach, strengths, and weaknesses. Here’s a breakdown of the most common types of software development methodologies:

// 1. Waterfall Methodology
// Type: Linear/Sequential
// Description: A traditional, structured approach where each phase of the software development lifecycle (SDLC) must be completed before moving to the next phase.
// Phases: Requirements → Design → Implementation → Testing → Deployment → Maintenance
// Best For: Small, well-defined projects with stable requirements.
// Weakness: Inflexible; difficult to accommodate changes once development begins.
// 2. Agile Methodology
// Type: Iterative/Incremental
// Description: Focuses on delivering small, workable portions of the software regularly through short iterations (sprints). Emphasizes flexibility, collaboration, and frequent feedback.
// Phases: Iterative sprints that include Planning → Development → Testing → Review → Retrospective
// Best For: Projects with evolving requirements or where frequent customer feedback is needed.
// Weakness: Requires constant collaboration; can be challenging to manage in large teams without proper alignment.
// 3. Scrum
// Type: Agile Framework
// Description: A specific Agile framework that uses sprints (typically 1-4 weeks) and roles like Scrum Master, Product Owner, and Development Team to manage and deliver increments of a product.
// Best For: Agile teams working on product development that can be broken down into manageable tasks.
// Weakness: Requires disciplined team collaboration; without proper coordination, Scrum can fail.
// 4. Kanban
// Type: Agile Framework
// Description: Focuses on visualizing work, limiting work in progress (WIP), and optimizing flow. Uses a Kanban board (with columns like "To Do," "In Progress," and "Done") to track task progress.
// Best For: Continuous delivery, service-oriented environments, or teams that need flexibility in task prioritization.
// Weakness: Lacks specific timeframes like Scrum; without limits on work in progress, tasks can bottleneck.
// 5. Lean Development
// Type: Agile Framework
// Description: Inspired by Lean manufacturing, focuses on eliminating waste, optimizing processes, and delivering only what provides value to the customer. Prioritizes minimizing time and resources.
// Best For: Organizations that want to reduce inefficiencies and deliver customer value quickly.
// Weakness: Requires continuous improvement efforts; not suited for projects with highly formal structures.
// 6. DevOps
// Type: Agile/Continuous Integration & Delivery (CI/CD)
// Description: A culture and practice that emphasizes collaboration between software development (Dev) and IT operations (Ops) teams. The goal is to shorten the system development lifecycle while delivering features, fixes, and updates frequently in close alignment with business objectives.
// Best For: Teams focusing on continuous integration, automated testing, and rapid deployment.
// Weakness: Requires a mature infrastructure and high-level collaboration between teams.
// 7. Extreme Programming (XP)
// Type: Agile Methodology
// Description: Focuses on technical excellence, frequent releases, and continuous customer feedback. It encourages practices like pair programming, test-driven development (TDD), and refactoring.
// Best For: Projects with constantly changing requirements and teams that emphasize code quality.
// Weakness: Can be demanding and overwhelming if not adopted correctly; pair programming may not suit all teams.
// 8. Spiral Model
// Type: Iterative/Risk-driven
// Description: Combines elements of both iterative and Waterfall models. The project passes through four phases repeatedly (planning, risk analysis, engineering, and evaluation), making it highly adaptable to changes and risk management.
// Best For: Large, complex, and high-risk projects where risks need to be assessed continuously.
// Weakness: Can be expensive due to the focus on continuous risk analysis.
// 9. V-Model (Validation and Verification Model)
// Type: Sequential/Waterfall Variant
// Description: Similar to Waterfall but includes a corresponding testing phase for each development phase. For example, system design will have a corresponding system testing phase.
// Best For: Projects with clearly defined requirements and where testing is critical.
// Weakness: Rigid structure; difficult to adapt to changing requirements.
// 10. Rapid Application Development (RAD)
// Type: Iterative/Prototype-based
// Description: Emphasizes rapid prototyping over extensive planning. The goal is to quickly produce a working model of the software and refine it based on customer feedback.
// Phases: Requirements Planning → User Design → Construction → Cutover
// Best For: Projects that need to be delivered quickly with continuous customer involvement.
// Weakness: Not ideal for large, complex projects; can lead to scope creep without proper control.
// 11. Feature-Driven Development (FDD)
// Type: Agile Methodology
// Description: Combines the best of Agile methodologies but focuses on building and designing features. It breaks down development into smaller, client-valued features.
// Best For: Large teams working on feature-based systems where functionality can be delivered in increments.
// Weakness: Not suited for small teams or projects without distinct feature sets.
// 12. Incremental Model
// Type: Iterative/Incremental
// Description: Develops the system in small increments, with each increment building upon the previous one. Each phase produces a working version of the product, which is improved in subsequent phases.
// Best For: Projects where it’s important to deliver working software early.
// Weakness: Requires proper planning to avoid integration challenges later.
// 13. Prototyping Model
// Type: Iterative
// Description: Involves creating a prototype (a basic version of the system) early in the process to gather user feedback. The prototype is refined based on feedback until the final system is developed.
// Best For: Projects where user requirements are unclear or evolving.
// Weakness: Prototypes may create unrealistic expectations, and continuous changes can delay the final product.
// Summary
// Methodology	Type/	Best For/	Key Focus
// Waterfall /	(Linear/Sequential)  /	Small, well-defined projects with stable requirements /	Clear, fixed stages with heavy documentation
// Agile /	(Iterative/Incremental)  /	Projects with evolving requirements, customer feedback   /	Flexibility, customer collaboration
// Scrum /	Agile Framework	Teams delivering product increments in short sprints/	Sprint-based with defined roles and ceremonies
// Kanban/	Agile Framework	Continuous delivery and service-oriented work/	Visual task tracking and flow optimization
// Lean Development/	Agile Framework	Reducing waste and focusing on customer value/	Minimizing waste and maximizing efficiency
// DevOps/	Agile/CI-CD	Teams focusing on continuous delivery and automated testing	Collaboration between Dev and Ops
// Extreme/ Programming	Agile Methodology/	Projects with changing requirements and a focus on code quality	Technical excellence, TDD, pair programming
// Spiral/	Iterative/Risk-based/	Large, complex projects requiring continuous risk management/	Continuous risk assessment
// V-Model/	Waterfall Variant/	Projects with high focus on testing	Testing at each development phase
// Rapid Application Dev (RAD)/	Prototype-based	Projects needing fast delivery and iterative user feedback/	Rapid prototyping
// Feature-Driven Dev (FDD)/	Agile Methodology/	Feature-based systems requiring incremental delivery/	Feature-based progress tracking
