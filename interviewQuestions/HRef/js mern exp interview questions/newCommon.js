// Task 2: Add a search feature: 5 story points (moderate effort, requires coding and testing).
// Task 3: Implement user authentication: 13 story points (complex, involves backend work, security concerns, and testing).
// Summary
// Story points are a flexible, team-driven way to estimate the relative effort of tasks in Agile development. They help teams understand how much work they can take on, improve their estimation skills, and manage their workflow more efficiently. By using Jira to manage story points, teams can easily track progress and adjust their work as needed.

// ------------------  WaterFall  Model : -----
// The Waterfall model is one of the earliest and most traditional software development methodologies used in IT companies. Unlike Agile, which is iterative and flexible, the Waterfall model follows a linear, sequential approach where each phase of the development process must be completed before moving to the next.

// Key Characteristics of the Waterfall Model
// Linear Process: The Waterfall model is structured, meaning each phase flows into the next like a waterfall—hence the name. Once a phase is complete, you move to the next; there’s little room for going back.
// Phase-based: The project is divided into distinct phases, and each phase must be completed before moving forward.
// Documentation-heavy: Every phase is well-documented, and there’s a lot of emphasis on creating detailed specifications and requirements before development begins.
// No Overlapping Phases: Each phase has its own timeline and deliverables, and no phase overlaps with the other.

// Phases of the Waterfall Model
// Requirements Gathering and Analysis:

// In this phase, all the project requirements are collected, documented, and analyzed. The focus is on understanding the client’s needs fully before development starts.
// Output: A detailed requirement specification document.
// System Design:

// Based on the requirements, the system's architecture and design are created. This includes both high-level design (overall system architecture) and detailed design (specific components, data flow, etc.).
// Output: System design document with a blueprint for the entire software.
// Implementation (Coding):

// Developers take the design documents and start writing code to implement the system. Each component or module is developed, then integrated with other components to form the full system.
// Output: The actual source code of the software.
// Integration and Testing:

// Once coding is done, the software is integrated and thoroughly tested for defects, bugs, or issues. This includes both unit testing (testing individual modules) and system testing (testing the entire system).
// Output: A tested, integrated system.
// Deployment (Installation):

// After successful testing, the software is deployed to the client’s environment or put into production for use.
// Output: Working software deployed at the client's site or on live servers.
// Maintenance:

// After deployment, the software enters the maintenance phase where bugs or issues discovered by users are fixed. Additional features or improvements may also be added based on user feedback.
// Output: Updated and maintained software over time.

// Advantages of the Waterfall Model
// Simple and Easy to Use: The structured approach makes it easy to understand, follow, and manage, especially for small projects.
// Clear Objectives: Each phase has clear goals, timelines, and deliverables, which helps with planning and resource allocation.
// Well-Defined Documentation: Since every phase is documented in detail, it creates a clear record of decisions, requirements, and system design.
// Easy to Manage: The sequential nature allows project managers to monitor progress and ensure that each phase is fully completed before the next begins.

// Disadvantages of the Waterfall Model
// Inflexibility: One of the biggest issues is its rigidity. Once a phase is completed, it’s hard to go back and make changes. For example, if new requirements are discovered during the coding phase, it can be difficult and costly to incorporate them.
// Late Testing: Testing happens late in the process. This means issues or bugs may not be discovered until much later, potentially increasing the cost of fixing them.
// High Risk: The entire project can fail if a problem is discovered late in the process, as there's little room for error correction.
// Not Ideal for Complex Projects: In large or complex projects, the lack of flexibility can lead to delays or issues with adapting to changing requirements.
// Client Feedback Delayed: Since there’s no working product until the very end, feedback from stakeholders or clients is delayed, potentially leading to mismatched expectations.
// When to Use the Waterfall Model

// The Waterfall model is best suited for:

// Small projects: Where the requirements are well understood and unlikely to change.
// Well-defined projects: Where all specifications are clear from the start and there is little need for flexibility.
// Less complex projects: Where the scope and technology are straightforward, and changes during development are minimal.

// Summary
// In an IT company, the Waterfall model offers a structured and easy-to-follow approach, but it’s not suitable for projects where requirements frequently change. It works best when the scope and requirements are fixed, making it a good choice for smaller, well-understood projects. However, for dynamic projects that need flexibility and ongoing client feedback, Agile methodologies (like Scrum) are more effective.

