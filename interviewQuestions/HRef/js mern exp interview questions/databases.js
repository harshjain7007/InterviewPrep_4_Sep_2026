// Differance between SQL and NoSQL DataBase :-  When it comes to choosing a database the biggest decision is picking a relational (SQL) or non-relational (NoSQL) data structure. While both databases are viable options still there are certain key differences between the two that users must keep in mind when making a decision.
// Data Model:
// SQL: Table-based (rows and columns).
// NoSQL: Various models (document, key-value, column-family, graph).
// Schema:
// SQL: Predefined and rigid schema.
// NoSQL: Flexible and dynamic schema.
// Scalability:
// SQL: Primarily vertical scaling; horizontal scaling is complex.
// NoSQL: Designed for horizontal scaling.
// Consistency:
// SQL: Strong consistency (ACID compliance).
// NoSQL: Eventual consistency (some NoSQL databases can be configured for strong consistency).
// Query Language:
// SQL: Standardized query language (SQL).
// NoSQL: Varies by database (e.g., MongoDB uses MQL, Cassandra uses CQL).

// Use Cases:
// SQL: Structured data, complex transactions, and relational data (e.g., financial systems, CRM).
// NoSQL: Unstructured or semi-structured data, scalability, and performance (e.g., real-time analytics, content management, IoT).
// Choosing between SQL and NoSQL databases depends on the specific needs of your application, including data structure, scalability, and performance requirements.
