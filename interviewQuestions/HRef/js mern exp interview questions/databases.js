// ---- What is ORMS :-
// ORM stands for Object-Relational Mapping. It's a technique used in software development to facilitate the interaction between object-oriented programming languages and relational databases. ORMs allow developers to work with data in a database using objects in their code, without needing to write complex SQL queries.

// Key Features of ORM:
// Abstraction: ORM abstracts the database interaction and allows you to work with database tables as if they were objects in your code.
// Data Mapping: ORM maps classes in your code to database tables and maps object properties to table columns.
// CRUD Operations: You can easily perform Create, Read, Update, and Delete operations without needing to write SQL.
// Database Agnosticism: Many ORM tools allow switching between different database systems (like MySQL, PostgreSQL, or SQLite) with minimal code changes.

// Common ORM Libraries:
// JavaScript/Node.js: Sequelize, TypeORM, Mongoose (for MongoDB)

// ORMS simplify database interaction, especially in large applications, by providing an object-oriented approach to working with data.

